#!/bin/bash

# Функция валидации входных аргументов для Part 5
validate_args() {
    # 1. Проверяем количество параметров (должен быть ровно 1)
    if [ "$#" -ne 1 ]; then
        echo "Ошибка: Неверное количество параметров! Ожидается 1 параметр." >&2
        echo "Использование: $0 <1|2|3|4>" >&2
        echo "  1 — Все записи, отсортированные по коду ответа" >&2
        echo "  2 — Все уникальные IP, встречающиеся в записях" >&2
        echo "  3 — Все запросы с ошибками (код ответа 4xx или 5xx)" >&2
        echo "  4 — Все уникальные IP, встречающиеся среди ошибочных запросов" >&2
        return 1
    fi

    local mode="$1"

    # 2. Проверяем, что параметр является числом 1, 2, 3 или 4
    if ! [[ "$mode" =~ ^[1-4]$ ]]; then
        echo "Ошибка: Некорректный параметр '$mode'! Допустимые значения: 1, 2, 3, 4." >&2
        return 1
    fi

    return 0
}

# Функция проверки наличия файлов логов
check_log_files() {
    local log_dir="$1"
    local count
    count=$(find "$log_dir" -maxdepth 1 -name "nginx_*.log" 2>/dev/null | wc -l)

    if [ "$count" -eq 0 ]; then
        echo "Ошибка: Файлы логов не найдены в $log_dir!" >&2
        echo "Сначала запустите скрипт генерации логов из Part 4 (src/04/main.sh)." >&2
        return 1
    fi

    return 0
}

# Если скрипт запущен напрямую, а не через source
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    echo "Ошибка: Этот скрипт является модулем. Запускайте через main.sh" >&2
    exit 1
fi
