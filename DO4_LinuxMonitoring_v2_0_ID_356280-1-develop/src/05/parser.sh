#!/bin/bash

# ==============================================================================
# Модуль разбора логов Nginx с помощью awk
# В строке формата Combined:
# $1: IP-адрес
# $2, $3: Идентификаторы пользователя ("-", "-")
# $4, $5: Дата и время в квадратных скобках ([DD/Mon/YYYY:HH:MM:SS +0000])
# $6, $7, $8: HTTP-запрос ("GET /url HTTP/1.1")
# $9: Код ответа сервера (Status code, например 200, 404, 500)
# $10: Размер переданных данных в байтах
# $11: Referer
# $12+: User-Agent
# ==============================================================================

# Режим 1: Все записи, отсортированные по коду ответа
parse_mode_1() {
    local log_files=("$@")
    # awk считывает строки из всех файлов, а sort -k 9 -n сортирует по 9-й колонке (код ответа) как числа
    awk '{ print $0 }' "${log_files[@]}" | sort -k 9 -n
}

# Режим 2: Все уникальные IP, встречающиеся в записях
parse_mode_2() {
    local log_files=("$@")
    # $1 - IP-адрес, sort -u оставляет только уникальные адреса
    awk '{ print $1 }' "${log_files[@]}" | sort -u
}

# Режим 3: Все запросы с ошибками (код ответа — 4xx или 5xx)
parse_mode_3() {
    local log_files=("$@")
    # $9 - код ответа, отбираем строки с кодами 4xx (400-499) и 5xx (500-599)
    awk '$9 ~ /^[45][0-9]{2}$/ { print $0 }' "${log_files[@]}"
}

# Режим 4: Все уникальные IP, которые встречаются среди ошибочных запросов
parse_mode_4() {
    local log_files=("$@")
    # Фильтруем строки с ошибками (коды 4xx и 5xx), извлекаем IP ($1) и выводим уникальные
    awk '$9 ~ /^[45][0-9]{2}$/ { print $1 }' "${log_files[@]}" | sort -u
}

# Главная функция обработки логов
process_logs() {
    local mode="$1"
    local log_dir="$2"

    # Получаем все файлы логов в массив
    local log_files=("$log_dir"/nginx_*.log)

    case "$mode" in
        1)
            parse_mode_1 "${log_files[@]}"
            ;;
        2)
            parse_mode_2 "${log_files[@]}"
            ;;
        3)
            parse_mode_3 "${log_files[@]}"
            ;;
        4)
            parse_mode_4 "${log_files[@]}"
            ;;
    esac
}

# Если скрипт запущен напрямую, а не через source
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    echo "Ошибка: Этот скрипт является модулем. Запускайте через main.sh" >&2
    exit 1
fi
