#!/bin/bash

# Функция валидации аргументов для Part 2
validate_args() {
    # 1. Проверяем количество параметров (должно быть ровно 3)
    if [ "$#" -ne 3 ]; then
        echo "Ошибка: Неверное количество параметров! Ожидается 3 параметра."
        echo "Пример запуска: $0 az az.az 3Mb"
        return 1
    fi

    local dir_chars="$1"
    local file_pattern="$2"
    local file_size="$3"

    # 2. Проверка параметра 1 (буквы для папок - только английские буквы, не более 7 знаков)
    if ! [[ "$dir_chars" =~ ^[a-zA-Z]{1,7}$ ]]; then
        echo "Ошибка: Параметр 1 ($dir_chars) должен содержать от 1 до 7 букв английского алфавита."
        return 1
    fi

    # 3. Проверка параметра 2 (буквы для имени и расширения файлов, например az.az)
    # Имя: до 7 букв, Расширение: до 3 букв
    if ! [[ "$file_pattern" =~ ^[a-zA-Z]{1,7}\.[a-zA-Z]{1,3}$ ]]; then
        echo "Ошибка: Параметр 2 ($file_pattern) должен иметь формат 'имя.расширение' (имя до 7 букв, расширение до 3 букв)."
        return 1
    fi

    # 4. Проверка параметра 3 (размер файлов в Мегабайтах, не более 100Mb)
    if ! [[ "$file_size" =~ ^([0-9]+)(mb|MB|Mb|mB)$ ]]; then
        echo "Ошибка: Параметр 3 ($file_size) должен быть в формате 'NMb' (например, 3Mb или 100Mb)."
        return 1
    fi

    # Извлекаем числовое значение размера в Mb
    local size_num="${BASH_REMATCH[1]}"
    if [ "$size_num" -le 0 ] || [ "$size_num" -gt 100 ]; then
        echo "Ошибка: Размер файла ($file_size) должен быть больше 0 и не более 100Mb."
        return 1
    fi

    return 0
}

# Если скрипт запущен напрямую, а не через source
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    echo "Ошибка: Этот скрипт является модулем. Запускайте через main.sh"
    exit 1
fi
