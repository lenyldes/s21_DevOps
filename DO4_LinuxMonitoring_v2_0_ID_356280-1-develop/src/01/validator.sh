#!/bin/bash

# Функция валидации входных параметров
validate_args() {
    # 1. Проверяем количество параметров (должно быть ровно 6)
    if [ "$#" -ne 6 ]; then
        echo "Ошибка: Неверное количество параметров! Ожидается 6 параметров."
        echo "Пример запуска: $0 /opt/test 4 az 5 az.az 3kb"
        return 1
    fi

    local target_dir="$1"
    local dir_count="$2"
    local dir_chars="$3"
    local file_count="$4"
    local file_pattern="$5"
    local file_size="$6"

    # 2. Проверка параметра 1 (абсолютный путь)
    if [[ "$target_dir" != /* ]]; then
        echo "Ошибка: Параметр 1 ($target_dir) должен быть абсолютным путем (начинаться с /)."
        return 1
    fi

    # 3. Проверка параметра 2 (количество папок - целое положительное число)
    if ! [[ "$dir_count" =~ ^[0-9]+$ ]] || [ "$dir_count" -le 0 ]; then
        echo "Ошибка: Параметр 2 ($dir_count) должен быть положительным целым числом."
        return 1
    fi

    # 4. Проверка параметра 3 (буквы для папок - только английские буквы, не более 7 знаков)
    if ! [[ "$dir_chars" =~ ^[a-zA-Z]{1,7}$ ]]; then
        echo "Ошибка: Параметр 3 ($dir_chars) должен содержать от 1 до 7 букв английского алфавита."
        return 1
    fi

    # 5. Проверка параметра 4 (количество файлов в каждой папке - целое положительное число)
    if ! [[ "$file_count" =~ ^[0-9]+$ ]] || [ "$file_count" -le 0 ]; then
        echo "Ошибка: Параметр 4 ($file_count) должен быть положительным целым числом."
        return 1
    fi

    # 6. Проверка параметра 5 (буквы для имени и расширения файлов, например az.az)
    # Имя: до 7 букв, Расширение: до 3 букв
    if ! [[ "$file_pattern" =~ ^[a-zA-Z]{1,7}\.[a-zA-Z]{1,3}$ ]]; then
        echo "Ошибка: Параметр 5 ($file_pattern) должен иметь формат 'имя.расширение' (имя до 7 букв, расширение до 3 букв)."
        return 1
    fi

    # 7. Проверка параметра 6 (размер файлов в килобайтах, не более 100kb)
    if ! [[ "$file_size" =~ ^([0-9]+)(kb|KB|Kb|kB)$ ]]; then
        echo "Ошибка: Параметр 6 ($file_size) должен быть в формате 'Nkb' (например, 3kb или 100kb)."
        return 1
    fi

    # Извлекаем числовое значение размера
    local size_num="${BASH_REMATCH[1]}"
    if [ "$size_num" -le 0 ] || [ "$size_num" -gt 100 ]; then
        echo "Ошибка: Размер файла ($file_size) должен быть больше 0 и не более 100kb."
        return 1
    fi

    return 0
}

# Если скрипт запущен напрямую, а не через source
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    echo "Ошибка: Этот скрипт является модулем. Запускайте через main.sh"
    exit 1
fi
