#!/bin/bash

# Проверка количества параметров
if [ $# -ne 4 ]; then
    echo "ОШИБКА: нужно передать ровно четыре параметра"
    echo "Использование: ./main.sh {column1_background} {column1_font_color} {column2_background} {column2_font_color}"
    exit 1
fi

col1_bg=$1
col1_fg=$2
col2_bg=$3
col2_fg=$4

# Проверка диапазона всех параметров (1..6)
for p in "$col1_bg" "$col1_fg" "$col2_bg" "$col2_fg"; do
    if ! [[ "$p" =~ ^[1-6]$ ]]; then
        echo "ОШИБКА: параметр '$p' вне диапазона 1..6"
        echo "Использование: ./main.sh {1..6} {1..6} {1..6} {1..6}"
        echo "Цвета: 1 — white, 2 — red, 3 — green, 4 — blue, 5 — purple, 6 — black"
        exit 1
    fi
done

# Проверка: фон и шрифт одного столбца не должны совпадать
if [ "$col1_bg" = "$col1_fg" ]; then
    echo "ОШИБКА: фон и шрифт столбца 1 совпадают (значение $col1_bg)"
    echo "Шрифт и фон одного столбца не должны совпадать. Запустите скрипт с другими параметрами."
    exit 1
fi
if [ "$col2_bg" = "$col2_fg" ]; then
    echo "ОШИБКА: фон и шрифт столбца 2 совпадают (значение $col2_bg)"
    echo "Шрифт и фон одного столбца не должны совпадать. Запустите скрипт с другими параметрами."
    exit 1
fi